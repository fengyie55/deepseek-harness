/** Validate persisted answers and derive chart positions without changing source cells. */
import { z } from 'zod'
import type { InteractiveAnswer } from '@deepseek-ai/dsh-tool-interactive-answer/types'
import type { ToolResultNode } from '@deepseek-ai/dsh-client-ui-chat/client'
import type { JsonValue } from '@deepseek-ai/dsh-util-values'

const cell = z.union([z.string(), z.number(), z.boolean(), z.null()])
const answerSchema = z.object({
  format: z.literal('interactive-answer'),
  version: z.literal(1), title: z.string(), kind: z.enum(['table', 'trend', 'pareto', 'timeline']),
  columns: z.array(z.object({ title: z.string(), path: z.array(z.string()) })).min(1),
  rows: z.array(z.array(cell)).min(1),
  labelColumn: z.number().int().nonnegative(), valueColumn: z.number().int().nonnegative(), unit: z.string(),
  source: z.object({ callId: z.string(), name: z.string(), seq: z.number().int().nonnegative(), arguments: z.json(), document: z.json() }),
  jsonPath: z.array(z.string()).optional(),
  rowsPath: z.array(z.string()),
}).refine(answer => answer.labelColumn < answer.columns.length && answer.valueColumn < answer.columns.length
  && answer.rows.every(row => row.length === answer.columns.length))

/** Browser-admitted data retains the original call id as wire text. */
export type Answer = Omit<InteractiveAnswer, 'source' | 'jsonPath'> & Pick<z.infer<typeof answerSchema>, 'source' | 'jsonPath'>

function selectionDocument(answer: Answer): JsonValue | undefined {
  let value = answer.source.document
  if (answer.jsonPath === undefined) return value
  for (const key of answer.jsonPath) {
    if (value === null || typeof value !== 'object' || !Object.hasOwn(value, key)) return undefined
    const child: JsonValue | undefined = Array.isArray(value) ? value[Number(key)] : value[key]
    if (child === undefined) return undefined
    value = child
  }
  if (typeof value !== 'string') return undefined
  try {
    const parsed = z.json().safeParse(JSON.parse(value))
    return parsed.success ? parsed.data : undefined
  } catch (error) {
    if (error instanceof SyntaxError) return undefined
    throw error
  }
}

/**
 * Retain query status and coverage beside a selected row, without repeating source row arrays.
 * @param answer - validated source snapshot.
 * @returns original envelope fields other than data rows.
 */
export function evidenceContext(answer: Answer): Record<string, JsonValue> {
  const doc = selectionDocument(answer)
  if (doc == null || typeof doc !== 'object' || Array.isArray(doc)) return {}
  const fields = new Set(['status', 'warnings', 'coverage', 'complete', 'readiness', 'stop_reason',
    'quality', 'limitations', 'time_range', 'time_zone', 'timezone', 'unit', 'units', 'error'])
  const select = (record: Record<string, JsonValue>) => Object.fromEntries(Object.entries(record).filter(([key]) => fields.has(key)))
  const context = select(doc)
  for (const name of ['data', 'metadata']) {
    const nested = doc[name]
    if (nested === null || typeof nested !== 'object' || Array.isArray(nested)) continue
    const selected = select(nested)
    if (Object.keys(selected).length > 0) context[name] = selected
  }
  return context
}

/** Localized labels for the normal user message generated by a card action. */
export interface FollowupLabels {
  instruction: string
  source: string
  originalRow: string
  query: string
  coverage: string
  unit: string
}

/**
 * Read direct metadata or nested-call JSON, preserving generic output for unsupported values.
 * @param block - settled tool result.
 * @returns validated answer or null.
 */
export function readAnswer(block: Pick<ToolResultNode, 'isError' | 'meta' | 'content'>): Answer | null {
  if (block.isError) return null
  let value: unknown = block.meta
  if (value === undefined) {
    const text = block.content.length === 1 ? block.content[0] : undefined
    if (text?.type !== 'text') return null
    try {
      value = JSON.parse(text.text)
    } catch (error) {
      if (error instanceof SyntaxError) return null
      throw error
    }
  }
  const parsed = answerSchema.safeParse(value)
  if (!parsed.success) return null
  const answer = parsed.data
  if (selectionDocument(answer) === undefined) return null
  if ((answer.kind === 'trend' || answer.kind === 'pareto') && answer.rows.some((row) => {
    const value = row[answer.valueColumn]
    return value !== null && (typeof value !== 'number' || (answer.kind === 'pareto' && value < 0))
  })) return null
  return answer
}

/**
 * Compose an explicit follow-up with the selected original row and evidence identity.
 * @param answer - validated answer.
 * @param rowIndex - original source row index.
 * @param labels - locale-owned user action and evidence labels.
 * @returns a prompt for this card's owning session.
 */
export function followupText(answer: Answer, rowIndex: number, labels: FollowupLabels): string {
  const row = answer.rows[rowIndex]
  if (row === undefined) throw new Error('Selected source row is unavailable')
  return [labels.instruction, '', answer.title,
    ...answer.columns.map((column, index) => `${column.title}: ${JSON.stringify(row[index])}`),
    ...answer.unit === '' ? [] : [`${labels.unit}: ${answer.unit}`], '',
    `${labels.source}: ${answer.source.name} (${answer.source.callId})`,
    `${labels.originalRow}: ${rowIndex + 1}`,
    `${labels.query}: ${typeof answer.source.arguments === 'string' ? answer.source.arguments : JSON.stringify(answer.source.arguments)}`,
    `${labels.coverage}: ${JSON.stringify(evidenceContext(answer))}`,
  ].join('\n')
}

/**
 * Sort Pareto rows by observed value while retaining source indexes; other views keep source order.
 * @param answer - validated answer.
 * @returns source indexes in display order.
 */
export function orderedRows(answer: Answer): { index: number; row: Answer['rows'][number] }[] {
  const entries = answer.rows.map((row, index) => ({ row, index }))
  if (answer.kind !== 'pareto') return entries
  return entries.sort((a, b) => {
    const left = a.row[answer.valueColumn]
    const right = b.row[answer.valueColumn]
    if (left === null) return right === null ? a.index - b.index : 1
    if (right === null) return -1
    return Number(right) - Number(left) || a.index - b.index
  })
}
